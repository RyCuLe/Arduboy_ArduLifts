// --- CUSTOM FONT INLINE IMPLEMENTATIONS ---

inline uint8_t getCustomCharWidth(char c) {
  if (c == 'I') return 3;
  if (c == 'M' || c == 'N' || c == 'O' || c == 'Q' || c == 'T' || c == 'W' || c == 'X' || c == '^' || c == 'v' || c == '!') return 5;
  return 4;
}

inline void drawCustomChar(int16_t x, int16_t y, char c) {
  int index = -1;

  if (c >= '0' && c <= '9') {
    index = c - '0';
  } else if (c >= 'A' && c <= 'Z') {
    index = 10 + (c - 'A');
  } else if (c == '^') {
    index = 36;
  } else if (c == 'v') {
    index = 37;
  } else if (c == '!') {
    index = 38;
  }

  if (index != -1) {
    arduboy.drawBitmap(x, y, Font[index], 5, 5, WHITE);
  }
}

inline void drawCustomString(int16_t x, int16_t y, const char* text) {
  while (*text) {
    if (*text == ' ') {
      x += 3;
    } else {
      drawCustomChar(x, y, *text);
      x += getCustomCharWidth(*text) + 1;
    }
    text++;
  }
}

inline void drawCustomNum(int16_t x, int16_t y, int num) {
  char buf[8];
  itoa(num, buf, 10);
  drawCustomString(x, y, buf);
}

inline uint8_t getCustomStringWidth(const char* text) {
  uint8_t w = 0;
  while (*text) {
    if (*text == ' ') {
      w += 3;
    } else {
      w += getCustomCharWidth(*text) + 1;
    }
    text++;
  }
  return (w > 0) ? (w - 1) : 0;
}

inline uint8_t getCustomNumWidth(int num) {
  char buf[8];
  itoa(num, buf, 10);
  return getCustomStringWidth(buf);
}

